#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
for old in Cargo.toml Cargo.lock rustfmt.toml clippy.toml crates src/rust src/bridge; do
  if [[ -e "$root/$old" ]]; then
    echo "legacy Rust path in active Lightcept repo: $old" >&2
    exit 1
  fi
done

if find "$root/src" -type f -name '*.rs' -print -quit | grep -q .; then
  echo "Rust source remains in the active Cyna tree" >&2
  exit 1
fi

if grep -Eq 'cargo|liblightcept_ceiv_adapter|dlopen|dlsym|lc_ceiv_' \
  "$root/src/ui/ceiv/build.sh" "$root/src/ui/ceiv/app.json" "$root/src/ui/ceiv/native/preview_plugin.m"; then
  echo "Ceiv still references the retired Rust adapter" >&2
  exit 1
fi

if [[ -n "$(find "$root/src/engine" -type f -name '*.cy' -exec grep -l -E 'export c\(' {} +)" ]]; then
  echo "engine C exports remain after the Cyna package migration" >&2
  exit 1
fi
if rg -n '\bc_(size_t|uint|ushort|ullong|long|char)\b' "$root/src/engine" --glob '*.cy'; then
  echo "engine dimensions and samples must use Cyna types" >&2
  exit 1
fi
if rg -n '\bc_uchar\b|\bc fn\(' "$root/src/engine" --glob '*.cy'; then
  echo "engine cancellation must use Cyna callback types" >&2
  exit 1
fi
if rg -n '\bc_(int|float|double)\b|extern c\(' "$root/src/engine" --glob '*.cy'; then
  echo "engine statuses must use Cyna types" >&2
  exit 1
fi
python3 "$root/scripts/check-engine-boundaries.py"
python3 "$root/scripts/test-engine-boundaries.py" >/dev/null

if rg -n 'export c\(' "$root/src" --glob '*.cy' --glob '!**/generated/**' --glob '!ceiv_callbacks.cy' --glob '!ceiv_commands.cy'; then
  echo "active Lightcept C exports must be generated by Ceiv" >&2
  exit 1
fi
for retired in contract desktop intent project; do
  if [[ -d "$root/src/$retired" ]] && find "$root/src/$retired" -name '*.cy' -print -quit | rg -q .; then
    echo "retired Rust host module remains in active Cyna package: $retired" >&2
    exit 1
  fi
done

if rg -n 'extern c\(' "$root/src/ui/ceiv/src" --glob '*.cy' --glob '!**/generated/**' --glob '!native_preview.cy'; then
  echo "native provider imports must stay in native_preview.cy" >&2
  exit 1
fi
if rg -n 'export c\("lightcept_cyna_' "$root/src/ui/ceiv/src" --glob '*.cy' --glob '!**/generated/**' --glob '!ceiv_callbacks.cy'; then
  echo "native callback exports must be generated by Ceiv" >&2
  exit 1
fi
if rg -n 'export c\(' "$root/src/ui/ceiv/src" --glob '*.cy' --glob '!**/generated/**' --glob '!ceiv_callbacks.cy' --glob '!ceiv_commands.cy'; then
  echo "app C exports must be generated by Ceiv" >&2
  exit 1
fi
if rg -n '\bc_[A-Za-z_]+\b|\bextern c\(|\bexport c\(' \
  "$root/src/ui/ceiv/src/app.cy" "$root/src/ui/ceiv/src/document_registry.cy" \
  "$root/src/ui/ceiv/src/dng/camera_open.cy" "$root/src/ui/ceiv/src/dng/preview_callbacks.cy"; then
  echo "app workflow types must not expose the C ABI" >&2
  exit 1
fi
